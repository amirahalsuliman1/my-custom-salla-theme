/**
 * Writes src/views/components/js-translations.twig — the theme's own locale
 * strings that its JavaScript asks for, rendered by Twig so salla.lang has them.
 *
 * WHY THIS EXISTS. On the storefront, salla.lang holds only the platform's
 * translations (blocks, common, pages, …). The theme's src/locales files reach
 * Twig's trans() but never salla.lang, so every `salla.lang.get('theme.…')`
 * returned its own key — quick view printed «theme.common.was_price», toasts and
 * labels likewise. Found on the demo store 2026-10-13; the tests never saw it
 * because each stubs its translations.
 *
 * WHAT IT DOES. Collects every 'theme.…' string literal in src/assets/js (keys
 * chosen by a ternary or held in a variable are still written as literals
 * somewhere), skips `theme.settings.*` — those are salla.config reads, not
 * translations — and writes a partial that renders each through trans() and
 * hands them to salla.lang once the SDK and its messages have loaded.
 *
 *   node scripts/js-translations.mjs           write the partial
 *   node scripts/js-translations.mjs --check   fail if it is out of date
 */
import fs from 'node:fs'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const JS_DIR = path.join(ROOT, 'src/assets/js')
const OUT = path.join(ROOT, 'src/views/components/js-translations.twig')
const KEY = /['"`](theme\.[a-z0-9_]+(?:\.[a-z0-9_]+)+)['"`]/g

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) return walk(full)
    return entry.name.endsWith('.js') ? [full] : []
  })
}

export function collectKeys() {
  const keys = new Set()
  for (const file of walk(JS_DIR)) {
    for (const match of fs.readFileSync(file, 'utf8').matchAll(KEY)) {
      if (!match[1].startsWith('theme.settings.')) keys.add(match[1])
    }
  }
  return [...keys].sort()
}

export function render(keys) {
  const entries = keys
    .map((key) => `        ${JSON.stringify(key)}: {{ trans('${key}')|json_encode|raw }}`)
    .join(',\n')

  return `{#
  GENERATED by scripts/js-translations.mjs — do not edit by hand; run
  \`node scripts/js-translations.mjs\` after adding a 'theme.…' key to the JS.

  The theme's own strings that its JavaScript reads through salla.lang.get().
  salla.lang on the storefront carries only the platform's translations, so
  these are rendered here by trans() and set into it once the SDK — loaded
  async, so not yet defined when this runs — and its messages are ready.
#}
<script data-cfasync="false">
    (function () {
        var strings = {
${entries}
        };
        function apply() {
            for (var key in strings) {
                if (Object.prototype.hasOwnProperty.call(strings, key)) salla.lang.set(key, strings[key]);
            }
        }
        (function wait(tries) {
            if (window.salla && salla.lang && typeof salla.lang.onLoaded === 'function') {
                salla.lang.onLoaded(apply);
            } else if (tries < 1000) {
                setTimeout(function () { wait(tries + 1); }, 10);
            }
        })(0);
    })();
</script>
`
}

const isMain =
  process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)

if (isMain) {
  const expected = render(collectKeys())
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
    if (actual !== expected) {
      console.error(
        '✗ src/views/components/js-translations.twig is out of date — run: node scripts/js-translations.mjs',
      )
      process.exit(1)
    }
    console.log('✓ js-translations.twig matches the keys the JS reads')
  } else {
    fs.writeFileSync(OUT, expected)
    console.log(`✓ wrote js-translations.twig — ${collectKeys().length} keys`)
  }
}
